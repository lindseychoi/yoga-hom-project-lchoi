import mongoose, { Schema, Document } from 'mongoose';
import { CLASS_TYPES } from './class.model';

export const PACKAGE_CATEGORIES = ['General', 'Senior'] as const;
/** Stored in numberOfClasses for an unlimited package. */
export const UNLIMITED = -1;
export const CLASS_COUNTS = [1, 4, 10, UNLIMITED];

export interface IPackage extends Document {
  packageId: string;
  packageName: string;
  packageCategory: (typeof PACKAGE_CATEGORIES)[number];
  numberOfClasses: number;
  classType: (typeof CLASS_TYPES)[number];
  startDate: Date;
  endDate: Date;
  price: number;
}

/** A package customers can buy (UC3). The readable packageId (PKG001) is generated by the service. */
const packageSchema = new Schema<IPackage>(
  {
    packageId: { type: String, required: true },
    packageName: { type: String, required: [true, 'Package name is required'], trim: true },
    packageCategory: {
      type: String,
      enum: PACKAGE_CATEGORIES,
      required: [true, 'Category is required'],
    },
    numberOfClasses: {
      type: Number,
      enum: { values: CLASS_COUNTS, message: 'Number of classes must be 1, 4, 10, or unlimited' },
      required: [true, 'Number of classes is required'],
    },
    classType: { type: String, enum: CLASS_TYPES, required: [true, 'Class type is required'] },
    startDate: { type: Date, required: [true, 'Start date is required'] },
    endDate: {
      type: Date,
      required: [true, 'End date is required'],
      validate: {
        // The package has to end after it starts. Only runs on save, where `this` is the package.
        validator(end: Date) {
          return end > (this as IPackage).startDate;
        },
        message: 'End date must be after the start date',
      },
    },
    price: {
      type: Number,
      required: [true, 'Price is required'],
      min: [0, 'Price cannot be negative'],
    },
  },
  { timestamps: true }
);

// No two packages share an ID
packageSchema.index({ packageId: 1 }, { unique: true });

export const Package = mongoose.model<IPackage>('Package', packageSchema);
